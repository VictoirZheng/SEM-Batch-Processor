# Interface translations (English / 简体中文).
# Usage: tr <- make_tr(lang); then tr(<key>, ...) with sprintf-style arguments

make_tr <- function(lang) {
  lang <- normalize_lang(lang)
  function(key, ...) {
    entry <- I18N[[key]]
    s <- if (is.null(entry)) key else entry[[lang]] %||% entry[["en"]]
    if (length(list(...)) > 0) do.call(sprintf, c(list(s), list(...))) else s
  }
}

